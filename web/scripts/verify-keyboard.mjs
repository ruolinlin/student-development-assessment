  await page.getByText('已保存 · 1 / 72 个回答', { exact: true }).waitFor();
  await Promise.all([page.waitForResponse(r => r.url().endsWith('/api/session') && r.request().method() === 'PUT'), page.keyboard.press('ArrowRight')]);
