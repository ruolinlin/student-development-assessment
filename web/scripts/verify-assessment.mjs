import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { fileURLToPath } from "node:url";
import fs from 'node:fs/promises';

const baseURL = process.env.PREVIEW_URL ?? 'http://localhost:5186';
const bank = JSON.parse(await fs.readFile(new URL('../data/question-bank.json', import.meta.url), 'utf8'));
await fs.mkdir(new URL('../outputs/', import.meta.url), { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL ?? "chrome" });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(baseURL);
  await page.getByRole('button', { name: '开始测评' }).waitFor();
  await page.screenshot({ path: fileURLToPath(new URL('../outputs/home-desktop.png', import.meta.url)), fullPage: true });
  await page.getByRole('button', { name: '开始测评' }).click();
  await page.getByLabel('我们怎么称呼你？').fill('测试同学');
  await page.screenshot({ path: fileURLToPath(new URL('../outputs/hello-desktop.png', import.meta.url)), fullPage: true });
  await page.getByRole('button', { name: '继续', exact: true }).click();
  await page.getByRole('heading', { name: bank.items[0].question_text, exact: true }).waitFor();
  await page.locator('label[for="answer-4"]').click();
  await page.getByText('已保存 · 1 / 72 个回答', { exact: true }).waitFor();
  await page.screenshot({ path: fileURLToPath(new URL('../outputs/question-desktop.png', import.meta.url)), fullPage: true });
  await page.getByRole('button', { name: '下一题', exact: true }).click();
  await page.getByRole('heading', { name: bank.items[1].question_text, exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: bank.items[1].question_text, exact: true }).waitFor();
  await page.getByRole('button', { name: '上一题', exact: true }).click();
  await page.getByRole('heading', { name: bank.items[0].question_text, exact: true }).waitFor();
  assert.equal(await page.locator('#answer-4').getAttribute('aria-checked'), 'true');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: fileURLToPath(new URL('../outputs/question-mobile.png', import.meta.url)), fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await context.setOffline(true);
  await page.locator('label[for="answer-5"]').click();
  await page.getByRole('alert').waitFor();
  await context.setOffline(false);
  await page.getByRole('button', { name: '下一题', exact: true }).click();
  await page.getByRole('heading', { name: bank.items[1].question_text, exact: true }).waitFor();
  let snapshot = await (await context.request.get(`${baseURL}/api/session`)).json();
  assert.equal(snapshot.session.answers.Q01, 5);
  for (let i = 1; i < bank.items.length; i++) {
    await page.getByRole('heading', { name: bank.items[i].question_text, exact: true }).waitFor();
    await page.locator(`label[for="answer-${1 + i % 5}"]`).click();
    await page.getByText(`已保存 · ${i + 1} / 72 个回答`, { exact: true }).waitFor();
    await page.getByRole('button', { name: i === 71 ? '完成第一部分' : '下一题', exact: true }).click();
  }
  await page.getByRole('heading', { name: '第一部分完成', exact: true }).waitFor();
  await page.screenshot({ path: fileURLToPath(new URL('../outputs/completion-mobile.png', import.meta.url)), fullPage: true });
  snapshot = await (await context.request.get(`${baseURL}/api/session`)).json();
  assert.equal(snapshot.session.status, 'completed');
  assert.equal(Object.keys(snapshot.session.answers).length, 72);
  await page.reload();
  await page.getByRole('heading', { name: '第一部分完成', exact: true }).waitFor();
  const revision = snapshot.session.revision;
  const invalid = await context.request.put(`${baseURL}/api/session`, { headers: { Origin: baseURL }, data: { revision, currentIndex: 71, answer: { item_id: 'Q72', value: 2.5 } } });
  assert.equal(invalid.status(), 400);
  const stale = await context.request.put(`${baseURL}/api/session`, { headers: { Origin: baseURL }, data: { revision: revision - 1, currentIndex: 71 } });
  assert.equal(stale.status(), 409);
  const external = await context.request.put(`${baseURL}/api/session`, { headers: { Origin: 'https://example.com' }, data: { revision, currentIndex: 71 } });
  assert.equal(external.status(), 403);
  const isolated = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const fresh = await isolated.newPage();
  await fresh.goto(baseURL);
  await fresh.getByRole('button', { name: '开始测评', exact: true }).waitFor();
  await fresh.screenshot({ path: fileURLToPath(new URL('../outputs/home-mobile.png', import.meta.url)), fullPage: true });
  await fresh.getByRole('button', { name: '开始测评', exact: true }).click();
  await fresh.screenshot({ path: fileURLToPath(new URL('../outputs/hello-mobile.png', import.meta.url)), fullPage: true });
  assert(await fresh.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: 72 real items, source text, persistence, refresh, edit, offline retry, mobile overflow, completion recovery, invalid score, stale revision, origin guard, isolated sessions, no runtime errors.');
} finally { await browser.close(); }
